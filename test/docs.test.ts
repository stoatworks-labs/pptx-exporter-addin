// The options reference in docs/USER-GUIDE.md is generated from the format
// definitions, so it can't drift from what the pane offers. This test fails
// when it has; `UPDATE_DOCS=1 npx vitest run test/docs.test.ts` rewrites it.
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { describe, expect, it } from 'vitest'
import { FORMATS } from '../src/formats'
import { GROUPS, type OptionDef } from '../src/formats/types'

const GUIDE = resolve(__dirname, '../docs/USER-GUIDE.md')
const START = '<!-- options:start (generated by test/docs.test.ts — edit the format definitions, not this) -->'
const END = '<!-- options:end -->'

function value(o: OptionDef): string {
  switch (o.type) {
    case 'select': return o.choices.map((c) => (c.value === o.default ? `**${c.label}**` : c.label)).join(' · ')
    case 'toggle': return o.default ? 'on' : 'off'
    case 'number':
    case 'slider': return `${o.min}–${o.max}${o.unit ? ` ${o.unit}` : ''}, default **${o.default}**`
    case 'color': return `default \`${o.default}\``
    case 'text': return o.default ? `default \`${o.default}\`` : 'empty by default'
  }
}

export function optionsReference(): string {
  const out: string[] = []
  for (const g of GROUPS) {
    const fs = FORMATS.filter((f) => f.group === g.id)
    if (!fs.length) continue
    out.push(`### ${g.label}`, '')
    for (const f of fs) {
      out.push(`#### ${f.label} (\`${f.ext}\`)`, '', f.blurb, '')
      if (!f.options.length) {
        out.push('No options.', '')
        continue
      }
      out.push('| Option | Choices | Notes |', '| --- | --- | --- |')
      for (const o of f.options) {
        const cond = o.when ? ' (shown when it applies)' : ''
        out.push(`| ${o.label}${cond} | ${value(o).replace(/\|/g, '\\|')} | ${(o.help ?? '').replace(/\|/g, '\\|')} |`)
      }
      out.push('')
    }
  }
  return out.join('\n').trim()
}

describe('docs/USER-GUIDE.md options reference', () => {
  it('matches the format definitions', () => {
    const guide = readFileSync(GUIDE, 'utf8')
    const a = guide.indexOf(START)
    const b = guide.indexOf(END)
    expect(a).toBeGreaterThan(-1)
    expect(b).toBeGreaterThan(a)
    const want = `${START}\n\n${optionsReference()}\n\n${END}`
    if (process.env.UPDATE_DOCS) {
      writeFileSync(GUIDE, guide.slice(0, a) + want + guide.slice(b + END.length))
      return
    }
    expect(guide.slice(a, b + END.length)).toBe(want)
  })
})
